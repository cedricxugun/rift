export async function applyTranslations() {
  const expectedKeys = new Set(sourceKeys);
  const prepared = [];
  // Validate every language before changing any generated file.
  for (const locale of locales) {
    const translation = { ...newKeys[locale], ...v2Translations[locale], ...v63Translations[locale], ...v65Translations[locale], ...v7Translations[locale] };
    const missing = sourceKeys.filter(key => typeof translation[key] !== 'string' || !translation[key].trim());
    const extras = Object.keys(translation).filter(key => !expectedKeys.has(key));
    if (missing.length || extras.length) {
      throw new Error(`${locale}: missing ${JSON.stringify(missing)}; extras ${JSON.stringify(extras)}`);
    }
    for (const key of sourceKeys) {
      const sourceTokens = [...key.matchAll(/\{\{[^}]+\}\}/g)].map(match => match[0]).sort();
      const targetTokens = [...translation[key].matchAll(/\{\{[^}]+\}\}/g)].map(match => match[0]).sort();
      if (JSON.stringify(sourceTokens) !== JSON.stringify(targetTokens)) {
        throw new Error(`${locale}: interpolation mismatch for ${key}`);
      }
    }
    prepared.push({ locale, translation: Object.fromEntries(sourceKeys.map(key => [key, translation[key]])) });
  }
  await fs.mkdir(LOCALES_DIR, { recursive: true });
  for (const { locale, translation } of prepared) {
    const filePath = path.join(LOCALES_DIR, `${locale}.json`);
    const text = JSON.stringify({ translation }, null, 2) + '\n';
    const previous = await fs.readFile(filePath, 'utf8').catch(() => '');
    if (text !== previous) {
      const temporaryPath = `${filePath}.tmp`;
      await fs.writeFile(temporaryPath, text, 'utf8');
      await fs.rename(temporaryPath, filePath);
    }
    console.log(`${locale}: ${sourceKeys.length} translations verified${text !== previous ? ' and applied' : ''}`);
  }
  return sourceKeys.length;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  applyTranslations().catch(error => { console.error(error); process.exitCode = 1; });
}
